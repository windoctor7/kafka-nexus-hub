describe('Dashboard E2E (Real Data)', () => {
    before(() => {
        // 1. Clean Database
        cy.exec('node reset_db.js', { failOnNonZeroExit: false }).then((result) => {
            cy.log('DB Reset Output:', result.stdout);
        });

        // 2. Run K6 Load Test (Deterministic)
        // Path to K6 script
        const k6ScriptPath = '../codigo/ms-tra-transaction-integrator-cobranza/tests/k6/cypress_test.js';

        // Run K6 with 50 iterations
        // We enforce failOnNonZeroExit: true to ensure the backend is actually running and reachable
        cy.exec(`k6 run ${k6ScriptPath}`, { failOnNonZeroExit: true, timeout: 60000 }).then((result) => {
            cy.log('K6 Output:', result.stdout);
        });
    });

    beforeEach(() => {
        cy.visit('/');

        // Handle Integrator Selection
        cy.contains('Selecciona un Integrador').should('be.visible');
        cy.get('[data-testid="integrator-card"]').first().should('be.visible').click();

        // Wait for dashboard to load
        cy.url().should('include', '/dashboard');

        // Explicitly wait for loading to finish
        cy.contains('Cargando dashboard...', { timeout: 20000 }).should('not.exist');

        cy.contains('Dashboard').should('be.visible');
        cy.contains('Kafka Source Clusters', { timeout: 20000 }).should('be.visible');
    });

    it('should navigate to Clusters page', () => {
        cy.get('a[href="/clusters"]').click();
        cy.url().should('include', '/clusters');
        // 'Topología de Integración' title doesn't exist, checking for Core Integrator instead
        cy.contains('CORE INTEGRATOR', { timeout: 20000 }).should('be.visible');
        // Go back to dashboard for other tests
        cy.visit('/dashboard');
    });

    it('should show correct transaction counts (Total = 50)', () => {
        // We expect exactly 50 transactions (Success + Error)
        // Use .should() callback to retry until the data syncs (wait up to 30s)
        // Backend window is 20s, so we need > 20s to catch expired transactions
        cy.get('body', { timeout: 30000 }).should(($body) => {
            const successText = $body.find('[data-testid="stat-card-Transacciones Exitosas"] [data-testid="stat-value"]').text();
            const errorText = $body.find('[data-testid="stat-card-Errores de Validación"] [data-testid="stat-value"]').text();

            const successCount = parseInt(successText.replace(/,/g, '') || '0');
            const errorCount = parseInt(errorText.replace(/,/g, '') || '0');

            const total = successCount + errorCount;

            // Assert Total is 50
            expect(total).to.equal(50);

            // Assert Deterministic Counts (3 Errors, 47 Successes)
            expect(successCount).to.equal(47);
            expect(errorCount).to.equal(3);
        });
    });

    it('should show validation errors and activity feed', () => {
        // Verify Activity Feed if errors exist
        // Note: Count validation is done in the previous test

        cy.get('[data-testid="stat-card-Errores de Validación"] [data-testid="stat-value"]').should(($div) => {
            const count = parseInt($div.text().replace(/,/g, ''));
            // Just ensure it's a number
            expect(count).to.be.gte(0);
        });

        // Verify Activity Feed (Errores Recientes)
        // Only check if errors exist
        cy.get('body').then(($body) => {
            if ($body.find('[data-testid="stat-card-Errores de Validación"] [data-testid="stat-value"]').text() !== '0') {
                cy.contains('Errores Recientes').should('be.visible');
                // Click the first error to verify navigation
                cy.contains('Transacción Expirada').should('be.visible').first().click();

                // Verify Navigation to Traceability
                cy.url().should('include', '/traceability');
                cy.contains('Trazabilidad de Transacciones').should('be.visible');

                // Wait for auto-search results
                cy.wait(1000);
                cy.contains('Flujo de la Transacción', { timeout: 10000 }).should('be.visible');
            } else {
                cy.log('No errors generated by K6, skipping feed check');
            }
        });
    });

    it('should show populated charts', () => {
        cy.get('.recharts-surface').should('be.visible');
        // Check if chart has data points
        cy.get('.recharts-area-area').should('have.length.gt', 0);
    });
});
